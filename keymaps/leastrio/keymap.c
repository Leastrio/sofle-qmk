static uint8_t animation_frame = 0;
static uint8_t animation_type = 0;

void render_pet(void) {
    for (uint8_t i = 0; i < 4; i++) {
        oled_set_cursor(0, i);
        oled_write_raw_P(cat_animations[animation_type][animation_frame][i], 33);
    }
}

uint32_t cat_animation_phases(uint32_t trigger_time, void *cb_arg) {
    if (get_current_wpm() <= 10) {
        animation_frame = (animation_frame + 1) % 2;
        animation_type = 0;
        return 500;
    } else if (get_current_wpm() <= 40) {
        animation_frame = (animation_frame + 1) % 3;
        animation_type = 1;
        return 500;
    } else if (get_current_wpm() <= 60) {
        animation_frame = (animation_frame + 1) % 2;
        animation_type = 2;
        return 500;
    } else {
        animation_frame = (animation_frame + 1) % 2;
        animation_type = 3;
        return 300;
    }
}

static void print_status_narrow(void) {
    oled_write_P(PSTR("\n\n"), false);
    switch (get_highest_layer(layer_state | default_layer_state)) {
        case _QWERTY:
            oled_write_ln_P(PSTR("Qwrt"), false);
            break;
        case _COLEMAK:
            oled_write_ln_P(PSTR("Clmk"), false);
            break;
        default:
            oled_write_P(PSTR("Mod\n"), false);
            break;
    }
    oled_write_P(PSTR("\n\n"), false);
    oled_write_ln_P(PSTR("LAYER"), false);
    switch (get_highest_layer(layer_state)) {
        case _QWERTY:
        case _COLEMAK:
            oled_write_P(PSTR("Base\n"), false);
            break;
        case _RAISE:
            oled_write_P(PSTR("Raise"), false);
            break;
        case _LOWER:
            oled_write_P(PSTR("Lower"), false);
            break;
        case _ADJUST:
            oled_write_P(PSTR("Adj\n"), false);
            break;
        default:
            oled_write_ln_P(PSTR("Undef"), false);
    }
    oled_write_P(PSTR("\n\n"), false);
    led_t led_usb_state = host_keyboard_led_state();
    oled_write_ln_P(PSTR("CPSLK"), led_usb_state.caps_lock);
}

bool oled_task_user(void) {
    if (is_keyboard_master()) {
        print_status_narrow();
    } else {
        render_pet();
        oled_set_cursor(0, 5);
        oled_write_P(PSTR("WPM: "), false);
        oled_write(get_u8_str(get_current_wpm(), '0'), false);
    }
    return false;
}

oled_rotation_t oled_init_user(oled_rotation_t rotation) {
    defer_exec(3000, cat_animation_phases, NULL);
    return OLED_ROTATION_270;
}

void suspend_power_down_user(void) {
    oled_off();
}

